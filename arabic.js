/* مكتبة المعالجة اللغوية والبحث للنصوص العربية */

/**
 * تطبيع النص العربي للبحث الدقيق:
 * - إزالة الحركات وعلامات التشكيل والتنوين
 * - إزالة التطويل (الكشيدة)
 * - توحيد الهمزات والألفات (أ, إ, آ, ٱ -> ا)
 * - توحيد التاء المربوطة (ة -> ه)
 * - توحيد الألف المقصورة والياء (ى -> ي)
 * - تحويل الأرقام المشرقية (٠-٩) إلى أرقام قياسية (0-9) للبحث
 */
export function normalizeArabic(text) {
  if (!text) return '';
  return String(text)
    .replace(/[٠-٩]/g, d => '٠١٢٣٤٥٦٧٨٩'.indexOf(d))
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/\u0640/g, '')
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .toLowerCase()
    .trim();
}

/**
 * تحويل الأرقام إلى الأرقام العربية المشرقية (٠-٩) للعرض الجمالي
 */
export function toArabicDigits(num) {
  const digits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(num).replace(/[0-9]/g, d => digits[+d]);
}
